#!/usr/bin/env bash
# Fail-closed firewall for a LANSeal Linux client (nftables).
# Policy: toward the protected LAN only DHCP, IKE/ESP/CA to the gateway and DNS to the router are allowed.
# Everything else addressed to / coming from LAN peers is dropped. Overlay addresses with no tunnel are
# unreachable (blackhole route), so nothing falls back to the plain LAN or the default route.
# Usage: firewall.sh --gateway-ip IP --ca-port N --protected CIDR[,CIDR] --overlay CIDR [--router IP] [--yes] | --remove
set -Eeuo pipefail
[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
DIR=/etc/lanseal/client; NFT="$DIR/firewall.nft"; UNIT=/etc/systemd/system/lanseal-client-firewall.service
GW="" CA_PORT="" PROT="" OVERLAY="" ROUTER="" YES=false REMOVE=false
while [ $# -gt 0 ]; do
  case "$1" in
    --gateway-ip) GW="$2"; shift 2;; --ca-port) CA_PORT="$2"; shift 2;; --protected) PROT="$2"; shift 2;;
    --overlay) OVERLAY="$2"; shift 2;; --router) ROUTER="$2"; shift 2;; --yes) YES=true; shift;; --remove) REMOVE=true; shift;;
    *) echo "unknown option $1" >&2; exit 2;;
  esac
done
if $REMOVE; then
  systemctl disable --now lanseal-client-firewall.service 2>/dev/null || true
  rm -f "$UNIT"; systemctl daemon-reload
  nft delete table inet lanseal_client 2>/dev/null || true
  [ -z "$OVERLAY" ] || ip route del unreachable "$OVERLAY" metric 4000 2>/dev/null || true
  echo "client firewall removed"; exit 0
fi
[ -n "$GW$CA_PORT$PROT$OVERLAY" ] && [ -n "$GW" ] && [ -n "$CA_PORT" ] && [ -n "$PROT" ] && [ -n "$OVERLAY" ] || { echo "missing arguments" >&2; exit 2; }
[ -n "$ROUTER" ] || ROUTER="$(ip -4 route show default | awk '/default/{print $3; exit}')"
python3 - "$GW" "$PROT" "$OVERLAY" "$ROUTER" "$CA_PORT" <<'PY' || exit 2
import ipaddress, sys
gw, prot, overlay, router, port = sys.argv[1:]
ipaddress.IPv4Address(gw); ipaddress.IPv4Address(router)
o = ipaddress.ip_network(overlay)
for p in prot.split(","):
    if o.overlaps(ipaddress.ip_network(p)):
        sys.exit(f"overlay {o} overlaps protected subnet {p}")
assert 1 <= int(port) <= 65535
PY
PROT_SET="{ ${PROT//,/, } }"
mkdir -p "$DIR"
[ ! -e "$NFT" ] || cp -a "$NFT" "$NFT.bak.$(date -u +%Y%m%dT%H%M%SZ)"
cat >"$NFT" <<NFTEOF
# LANSeal client fail-closed policy (generated by firewall.sh; own table only)
add table inet lanseal_client
delete table inet lanseal_client
table inet lanseal_client {
  chain output {
    type filter hook output priority -10; policy accept;
    udp sport 68 udp dport 67 accept
    ip daddr $GW udp dport { 500, 4500 } accept
    ip daddr $GW ip protocol esp accept
    ip daddr $GW tcp dport $CA_PORT accept
    ip daddr $ROUTER udp dport 53 accept
    ip daddr $ROUTER tcp dport 53 accept
    ip daddr $PROT_SET counter drop
  }
  chain input {
    type filter hook input priority -10; policy accept;
    udp sport 67 udp dport 68 accept
    ip saddr $GW udp sport { 500, 4500 } accept
    ip saddr $GW ip protocol esp accept
    ip saddr $GW tcp sport $CA_PORT accept
    ip saddr $ROUTER udp sport 53 accept
    ip saddr $ROUTER tcp sport 53 accept
    ip saddr $ROUTER icmp type { destination-unreachable, time-exceeded } accept
    ip saddr $PROT_SET counter drop
  }
}
NFTEOF
chmod 0600 "$NFT"
nft -c -f "$NFT" || { echo "nft rejected the generated rules; nothing applied" >&2; exit 1; }
cat >"$UNIT" <<UNITEOF
[Unit]
Description=LANSeal client fail-closed firewall
Before=network-pre.target
Wants=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $NFT
ExecStart=/sbin/ip route replace unreachable $OVERLAY metric 4000
ExecStop=-/usr/sbin/nft delete table inet lanseal_client
ExecStop=-/sbin/ip route del unreachable $OVERLAY metric 4000

[Install]
WantedBy=multi-user.target
UNITEOF
systemctl daemon-reload
nft -f "$NFT"
ip route replace unreachable "$OVERLAY" metric 4000
if $YES; then keep=keep; else
  echo "Fail-closed rules are LIVE. Direct LAN access to peers (including SSH *into* this host from LAN peers) is now blocked."
  read -r -t 60 -p "Type 'keep' within 60 s to make them permanent, otherwise they are removed: " keep || keep=""
fi
if [ "$keep" = "keep" ]; then systemctl enable lanseal-client-firewall.service >/dev/null; echo "kept; enabled at boot"
else nft delete table inet lanseal_client; ip route del unreachable "$OVERLAY" metric 4000; echo "removed (not confirmed)"; fi
